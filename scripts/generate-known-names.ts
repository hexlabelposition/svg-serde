import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { svgElementAttributes } from "svg-element-attributes";
import { svgTagNames } from "svg-tag-names";

/**
 * Generates `src/known-names.ts` from `svg-tag-names` and
 * `svg-element-attributes`. Run `bun run generate` after updating them;
 * `test/known-names.test.ts` fails while the file is out of date.
 */
export const OUTPUT: string = fileURLToPath(
  new URL("../src/known-names.ts", import.meta.url),
);

/**
 * Namespace-qualified attributes common in SVG files, which
 * `svg-element-attributes` does not list.
 */
const QUALIFIED_ATTRIBUTES = [
  "xmlns",
  "xmlns:xlink",
  "xlink:actuate",
  "xlink:arcrole",
  "xlink:href",
  "xlink:role",
  "xlink:show",
  "xlink:title",
  "xlink:type",
  "xml:base",
  "xml:lang",
  "xml:space",
];

export function generateKnownNames(): string {
  const elements = unique(svgTagNames);
  const attributes = unique([
    ...Object.values(svgElementAttributes).flat(),
    ...QUALIFIED_ATTRIBUTES,
  ]);

  return `// Generated by scripts/generate-known-names.ts. Do not edit.

/**
 * Standard SVG element names, from \`svg-tag-names\`.
 */
export type KnownSvgElementName =
${union(elements)};

/**
 * Standard SVG attribute names, from \`svg-element-attributes\`, plus common
 * \`xmlns\`, \`xlink\`, and \`xml\` attributes.
 */
export type KnownSvgAttributeName =
${union(attributes)};
`;
}

function unique(names: readonly string[]): string[] {
  return [...new Set(names)].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

function union(names: string[]): string {
  return names.map((name) => `  | ${JSON.stringify(name)}`).join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, generateKnownNames());
}
